def _vaastav_kind(path: str) -> str:
    if path.endswith("merged_gw.csv"):
        return "player_fixture"
    if path.endswith("fixtures.csv"):
        return "fixtures"
    if path.endswith("players_raw.csv"):
        return "player_identity"
    return "teams"


