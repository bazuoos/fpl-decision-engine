@dataclass(frozen=True)
class HistoricalSource:
    season: str
    repository: str
    commit: str
    path: str
    sha256: str
    kind: str
    gameweek: int | None = None

    @property
    def url(self) -> str:
        return (
            f"https://raw.githubusercontent.com/{self.repository}/"
            f"{self.commit}/{self.path}"
        )


